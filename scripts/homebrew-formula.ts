/**
 * Prints the Homebrew formula for a release. release.yml commits it to Formula/bun-toolkit.rb.
 *
 *   gh release view v0.1.0 --json assets > assets.json
 *   bun scripts/homebrew-formula.ts --version 0.1.0 --repo owner/name --assets assets.json --sums SHA256SUMS --private
 *
 * Private repos serve release assets only through the GitHub API, so --private points each url at
 * the API and sends HOMEBREW_GITHUB_API_TOKEN with the download.
 */
import { parseArgs } from "node:util";

export const PLATFORMS = ["darwin-arm64", "darwin-x64", "linux-arm64", "linux-x64"] as const;
export type Platform = (typeof PLATFORMS)[number];

export type FormulaAsset = { url: string; sha256: string };

export type FormulaInput = {
  version: string;
  repo: string;
  assets: Record<Platform, FormulaAsset>;
  privateDownload: boolean;
};

export type ReleaseAsset = { name: string; url: string; apiUrl: string };

export function parseSums(text: string): Map<string, string> {
  const sums = new Map<string, string>();
  for (const line of text.split("\n")) {
    const match = line.match(/^([0-9a-f]{64}) [ *](.+)$/);
    if (match?.[1] && match[2]) sums.set(match[2].trim(), match[1]);
  }
  return sums;
}

export function formulaAssets(
  release: readonly ReleaseAsset[],
  sums: Map<string, string>,
  privateDownload: boolean,
): Record<Platform, FormulaAsset> {
  const entries = PLATFORMS.map((platform) => {
    const name = `btk-${platform}`;
    const asset = release.find((a) => a.name === name);
    const sha256 = sums.get(name);
    if (!asset || !sha256) throw new Error(`Release is missing ${name} or its checksum`);
    return [platform, { url: privateDownload ? asset.apiUrl : asset.url, sha256 }] as const;
  });
  return Object.fromEntries(entries) as Record<Platform, FormulaAsset>;
}

function urlLine(asset: FormulaAsset, privateDownload: boolean): string {
  const headers = privateDownload ? ", headers: GITHUB_HEADERS.dup" : "";
  return `url "${asset.url}"${headers}\n      sha256 "${asset.sha256}"`;
}

function platformBlock(os: "macos" | "linux", input: FormulaInput): string {
  const prefix = os === "macos" ? "darwin" : "linux";
  const arm = input.assets[`${prefix}-arm64`];
  const intel = input.assets[`${prefix}-x64`];
  return `  on_${os} do
    on_arm do
      ${urlLine(arm, input.privateDownload)}
    end
    on_intel do
      ${urlLine(intel, input.privateDownload)}
    end
  end`;
}

export function renderFormula(input: FormulaInput): string {
  const headers = input.privateDownload
    ? `  GITHUB_HEADERS = [
    "Accept: application/octet-stream",
    "Authorization: Bearer #{ENV.fetch("HOMEBREW_GITHUB_API_TOKEN", "")}",
  ]

`
    : "";
  return `# Generated by scripts/homebrew-formula.ts when a release is published. Do not edit by hand.
class BunToolkit < Formula
  desc "Bun's native APIs in your terminal: images, hashes, data formats and more"
  homepage "https://github.com/${input.repo}"
  version "${input.version}"
  license "MIT"

${headers}${platformBlock("macos", input)}

${platformBlock("linux", input)}

  def install
    bin.install Dir["*"].first => "btk"
    bin.install_symlink "btk" => "bun-toolkit"
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/btk --version").strip
  end
end
`;
}

async function main(): Promise<void> {
  const { values } = parseArgs({
    args: Bun.argv.slice(2),
    options: {
      version: { type: "string" },
      repo: { type: "string" },
      assets: { type: "string" },
      sums: { type: "string" },
      private: { type: "boolean", default: false },
    },
  });
  if (!values.version || !values.repo || !values.assets || !values.sums) {
    throw new Error("Usage: --version <x.y.z> --repo <owner/name> --assets <file> --sums <file> [--private]");
  }
  const release = ((await Bun.file(values.assets).json()) as { assets: ReleaseAsset[] }).assets;
  const sums = parseSums(await Bun.file(values.sums).text());
  const assets = formulaAssets(release, sums, values.private);
  process.stdout.write(
    renderFormula({ version: values.version, repo: values.repo, assets, privateDownload: values.private }),
  );
}

if (import.meta.main) await main();
