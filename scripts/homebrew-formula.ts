/**
 * Writes the Homebrew formula for a release into the tap's Formula folder and prints its path.
 * A pre-release version (0.2.0-beta.1) goes to the opt-in bun-toolkit-beta formula, anything else
 * to bun-toolkit. The two conflict because both install `btk`.
 *
 *   gh release view v0.1.0 --json assets > assets.json
 *   bun scripts/homebrew-formula.ts --version 0.1.0 --repo owner/name --assets assets.json --sums SHA256SUMS --out Formula
 */
import { join } from "node:path";
import { parseArgs } from "node:util";

export const PLATFORMS = ["darwin-arm64", "darwin-x64", "linux-arm64", "linux-x64"] as const;
export type Platform = (typeof PLATFORMS)[number];

export type Channel = "stable" | "beta";

export type FormulaAsset = { url: string; sha256: string };

export type FormulaInput = {
  version: string;
  repo: string;
  assets: Record<Platform, FormulaAsset>;
};

export type ReleaseAsset = { name: string; url: string };

const FORMULA: Record<Channel, { name: string; className: string }> = {
  stable: { name: "bun-toolkit", className: "BunToolkit" },
  beta: { name: "bun-toolkit-beta", className: "BunToolkitBeta" },
};

export function channelFor(version: string): Channel {
  return version.includes("-") ? "beta" : "stable";
}

export function formulaName(version: string): string {
  return FORMULA[channelFor(version)].name;
}

export function parseSums(text: string): Map<string, string> {
  const sums = new Map<string, string>();
  for (const line of text.split("\n")) {
    const match = line.match(/^([0-9a-f]{64}) [ *](.+)$/);
    if (match?.[1] && match[2]) sums.set(match[2].trim(), match[1]);
  }
  return sums;
}

export function formulaAssets(
  release: readonly ReleaseAsset[],
  sums: Map<string, string>,
): Record<Platform, FormulaAsset> {
  const entries = PLATFORMS.map((platform) => {
    const name = `btk-${platform}`;
    const asset = release.find((a) => a.name === name);
    const sha256 = sums.get(name);
    if (!asset || !sha256) throw new Error(`Release is missing ${name} or its checksum`);
    return [platform, { url: asset.url, sha256 }] as const;
  });
  return Object.fromEntries(entries) as Record<Platform, FormulaAsset>;
}

function platformBlock(os: "macos" | "linux", assets: FormulaInput["assets"]): string {
  const prefix = os === "macos" ? "darwin" : "linux";
  const source = (asset: FormulaAsset) => `url "${asset.url}"\n      sha256 "${asset.sha256}"`;
  return `  on_${os} do
    on_arm do
      ${source(assets[`${prefix}-arm64`])}
    end
    on_intel do
      ${source(assets[`${prefix}-x64`])}
    end
  end`;
}

export function renderFormula(input: FormulaInput): string {
  const channel = channelFor(input.version);
  const other = FORMULA[channel === "beta" ? "stable" : "beta"].name;
  return `# Generated by scripts/homebrew-formula.ts when a release is published. Do not edit by hand.
class ${FORMULA[channel].className} < Formula
  desc "Bun's native APIs in your terminal: images, hashes, data formats and more"
  homepage "https://github.com/${input.repo}"
  version "${input.version}"
  license "MIT"

  conflicts_with "${other}", because: "both install btk"

${platformBlock("macos", input.assets)}

${platformBlock("linux", input.assets)}

  def install
    bin.install Dir["*"].first => "btk"
    bin.install_symlink "btk" => "bun-toolkit"
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/btk --version").strip
  end
end
`;
}

async function main(): Promise<void> {
  const { values } = parseArgs({
    args: Bun.argv.slice(2),
    options: {
      version: { type: "string" },
      repo: { type: "string" },
      assets: { type: "string" },
      sums: { type: "string" },
      out: { type: "string" },
    },
  });
  const { version, repo, out } = values;
  if (!version || !repo || !values.assets || !values.sums || !out) {
    throw new Error("Usage: --version <x.y.z> --repo <owner/name> --assets <file> --sums <file> --out <dir>");
  }
  const release = ((await Bun.file(values.assets).json()) as { assets: ReleaseAsset[] }).assets;
  const assets = formulaAssets(release, parseSums(await Bun.file(values.sums).text()));
  const path = join(out, `${formulaName(version)}.rb`);
  await Bun.write(path, renderFormula({ version, repo, assets }));
  process.stdout.write(`${path}\n`);
}

if (import.meta.main) await main();
